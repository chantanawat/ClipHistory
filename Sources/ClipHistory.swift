private struct ClipEntry: Codable, Equatable {
    var id: UUID
    var copiedAt: Date
    var lastPastedAt: Date? = nil
    var text: String?
    var imageData: Data?
    var imageType: String?
    var isPinned: Bool? = nil
}

private enum ClipboardWriter {
    static func write(text: String?, imageData: Data?, imageType: String?) -> Bool {
        let item = NSPasteboardItem()
        if let imageData, let imageType {
            _ = item.setData(imageData, forType: NSPasteboard.PasteboardType(imageType))
            if let tiff = NSImage(data: imageData)?.tiffRepresentation {
                _ = item.setData(tiff, forType: .tiff)
            }
        }
        if let text { _ = item.setString(text, forType: .string) }
        let board = NSPasteboard.general
        board.clearContents()
        return board.writeObjects([item])
    }
}

private final class HistoryStore {
    static let shared = HistoryStore()
    private(set) var entries: [ClipEntry] = []
    private let folder: URL
    private let file: URL
    private var lastChangeCount = -1
    private var pendingChangeCount: Int?
    private var pendingCaptureAttempts = 0

    private init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        folder = base.appendingPathComponent("ClipHistory", isDirectory: true)
        file = folder.appendingPathComponent("history.json")
        load()
    }

    func capturePasteboard() {
        let board = NSPasteboard.general
        let observedChangeCount = board.changeCount
        guard observedChangeCount != lastChangeCount else { return }
        if pendingChangeCount != observedChangeCount {
            pendingChangeCount = observedChangeCount
            pendingCaptureAttempts = 0
        }

        let types = Set(board.types?.map(\.rawValue) ?? [])
        let sensitiveTypes = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "net.antelle.keeweb"
        ]
        guard !sensitiveTypes.contains(where: types.contains) else {
            lastChangeCount = observedChangeCount
            pendingChangeCount = nil
            pendingCaptureAttempts = 0
            return
        }

        let text = board.string(forType: .string).flatMap { $0.isEmpty ? nil : $0 }
        var imageData: Data?
        var imageType: String?
        for candidate in board.types ?? [] {
            let typeName = candidate.rawValue.lowercased()
            let looksLikeImage = UTType(candidate.rawValue)?.conforms(to: .image) == true
                || ["png", "jpeg", "jpg", "tiff", "gif", "bmp", "webp", "heic", "jp2", "icns"].contains {
                    typeName.contains($0)
                }
            guard looksLikeImage, let data = board.data(forType: candidate), let decoded = NSImage(data: data) else { continue }
            if let tiff = decoded.tiffRepresentation,
               let bitmap = NSBitmapImageRep(data: tiff),
               let png = bitmap.representation(using: .png, properties: [:]) {
                imageData = png
                imageType = NSPasteboard.PasteboardType.png.rawValue
            } else {
                imageData = data
                imageType = candidate.rawValue
            }
            break
        }
        if imageData == nil, let decoded = NSImage(pasteboard: board),
           let tiff = decoded.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiff),
           let png = bitmap.representation(using: .png, properties: [:]) {
            imageData = png
            imageType = NSPasteboard.PasteboardType.png.rawValue
        }
        guard text != nil || imageData != nil else {
            pendingCaptureAttempts += 1
            if pendingCaptureAttempts >= 40 {
                lastChangeCount = observedChangeCount
                pendingChangeCount = nil
                pendingCaptureAttempts = 0
            }
            return
        }
        lastChangeCount = observedChangeCount
        pendingChangeCount = nil
        pendingCaptureAttempts = 0
        let entry = ClipEntry(id: UUID(), copiedAt: Date(), text: text, imageData: imageData, imageType: imageType)
        insert(entry)
    }

    @discardableResult
    func captureScreenshot(at url: URL) -> Bool {
        guard let image = NSImage(contentsOf: url),
              let tiff = image.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff),
              let png = bitmap.representation(using: .png, properties: [:]) else { return false }
        insert(ClipEntry(id: UUID(), copiedAt: Date(), text: nil, imageData: png, imageType: NSPasteboard.PasteboardType.png.rawValue))
        guard ClipboardWriter.write(text: nil, imageData: png, imageType: NSPasteboard.PasteboardType.png.rawValue) else { return false }
        lastChangeCount = NSPasteboard.general.changeCount
        pendingChangeCount = nil
        pendingCaptureAttempts = 0
        return true
    }

    func markCurrentPasteboardHandled() {
        lastChangeCount = NSPasteboard.general.changeCount
        pendingChangeCount = nil
        pendingCaptureAttempts = 0
    }

    func markPasted(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        var updated = entries.remove(at: index)
        updated.lastPastedAt = Date()
        entries.insert(updated, at: 0)
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    private func insert(_ entry: ClipEntry) {
        if let index = entries.firstIndex(where: { $0.text == entry.text && $0.imageData == entry.imageData }) {
            var existing = entries.remove(at: index)
            existing.copiedAt = entry.copiedAt
            existing.lastPastedAt = nil
            entries.insert(existing, at: 0)
        } else {
            entries.insert(entry, at: 0)
        }
        trimToLimit()
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    /// Drops the oldest unpinned entries beyond the configured limit; pinned entries are never trimmed.
    private func trimToLimit() {
        let limit = AppSettings.maxEntries
        var kept = 0
        entries = entries.filter { entry in
            if entry.isPinned == true { return true }
            kept += 1
            return kept <= limit
        }
    }

    func overflowCount(forLimit limit: Int) -> Int {
        max(0, entries.filter { $0.isPinned != true }.count - limit)
    }

    func applyLimitChange() {
        trimToLimit()
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    func togglePin(id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].isPinned = entries[index].isPinned == true ? nil : true
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    func delete(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    func clear() {
        entries.removeAll { $0.isPinned != true }
        save()
        NotificationCenter.default.post(name: .historyChanged, object: nil)
    }

    private func load() {
        guard let data = try? Data(contentsOf: file),
              let decoded = try? JSONDecoder().decode([ClipEntry].self, from: data) else { return }
        // Not trimmed on load: a lower limit only applies on the next copy or when changed in settings.
        entries = decoded.sorted { ($0.lastPastedAt ?? $0.copiedAt) > ($1.lastPastedAt ?? $1.copiedAt) }
    }

    private func save() {
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
            let data = try JSONEncoder().encode(entries)
            try data.write(to: file, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        } catch {
            NSLog("ClipHistory: could not save local history: %@", error.localizedDescription)
        }
    }
}


private enum AppSettings {
    static let defaultMaxEntries = 50
    static let maxEntriesRange = 1...120
    private static let maxEntriesKey = "maxEntries"
    private static let searchEnabledKey = "searchEnabled"

    static func clamp(_ value: Int) -> Int {
        min(max(value, maxEntriesRange.lowerBound), maxEntriesRange.upperBound)
    }

    static var maxEntries: Int {
        get { clamp(UserDefaults.standard.object(forKey: maxEntriesKey) as? Int ?? defaultMaxEntries) }
        set { UserDefaults.standard.set(clamp(newValue), forKey: maxEntriesKey) }
    }

    static var searchEnabled: Bool {
        get { UserDefaults.standard.object(forKey: searchEnabledKey) as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: searchEnabledKey) }
    }
}

/// Launch at login through a per-user LaunchAgent (SMAppService needs macOS 13+, this works on 11+).
private enum LaunchAtLogin {
    private static let label = "local.personal.ClipHistory"
    private static var plistURL: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Library/LaunchAgents/\(label).plist")
    }

    static var isEnabled: Bool { FileManager.default.fileExists(atPath: plistURL.path) }

    @discardableResult
    static func set(_ enabled: Bool) -> Bool {
        if !enabled {
            try? FileManager.default.removeItem(at: plistURL)
            return true
        }
        let plist: [String: Any] = [
            "Label": label,
            "ProgramArguments": ["/usr/bin/open", "-a", Bundle.main.bundlePath],
            "RunAtLoad": true,
            "LimitLoadToSessionType": "Aqua"
        ]
        do {
            try FileManager.default.createDirectory(at: plistURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
            try data.write(to: plistURL, options: .atomic)
            return true
        } catch {
            NSLog("ClipHistory: could not write launch agent: %@", error.localizedDescription)
            return false
        }
    }
}

/// One history row: preview text, optional thumbnail and pin/delete buttons that appear on hover.
/// The action buttons always reserve their width so long text can never run under them.
private final class ClipRowView: NSTableCellView {
    var onPaste: (() -> Void)?
    var onPin: (() -> Void)?
    var onDelete: (() -> Void)?

    private let pinButton: NSButton
    private let deleteButton: NSButton
    private let isPinned: Bool
    private weak var previewLabel: NSTextField?
    private var isHovering = false {
        didSet {
            guard isHovering != oldValue else { return }
            updateActions()
            needsDisplay = true
        }
    }

    private static func iconButton(symbol: String, label: String, tint: NSColor) -> NSButton {
        let base = NSImage(systemSymbolName: symbol, accessibilityDescription: label) ?? NSImage()
        let image = base.withSymbolConfiguration(NSImage.SymbolConfiguration(pointSize: 13, weight: .regular)) ?? base
        let button = NSButton(image: image, target: nil, action: nil)
        button.isBordered = false
        button.imagePosition = .imageOnly
        button.imageScaling = .scaleNone
        button.contentTintColor = tint
        button.toolTip = label
        button.setAccessibilityLabel(label)
        button.translatesAutoresizingMaskIntoConstraints = false
        button.widthAnchor.constraint(equalToConstant: 28).isActive = true
        button.heightAnchor.constraint(equalToConstant: 28).isActive = true
        return button
    }

    init(entry: ClipEntry, activity: String) {
        isPinned = entry.isPinned == true
        pinButton = Self.iconButton(
            symbol: isPinned ? "pin.fill" : "pin",
            label: isPinned ? "เลิกปักหมุด" : "ปักหมุดรายการนี้",
            tint: isPinned ? .controlAccentColor : .secondaryLabelColor
        )
        deleteButton = Self.iconButton(symbol: "trash", label: "ลบรายการนี้", tint: .secondaryLabelColor)
        super.init(frame: .zero)
        wantsLayer = true
        layer?.cornerRadius = 8
        pinButton.target = self
        pinButton.action = #selector(pinClicked)
        deleteButton.target = self
        deleteButton.action = #selector(deleteClicked)

        let timeLabel = NSTextField(labelWithString: activity)
        timeLabel.font = .systemFont(ofSize: 11, weight: .medium)
        timeLabel.textColor = .secondaryLabelColor
        timeLabel.lineBreakMode = .byTruncatingTail
        timeLabel.translatesAutoresizingMaskIntoConstraints = false

        let previewLabel = NSTextField(wrappingLabelWithString: Self.previewText(for: entry))
        previewLabel.font = .systemFont(ofSize: 13)
        previewLabel.textColor = .labelColor
        previewLabel.maximumNumberOfLines = 2
        previewLabel.lineBreakMode = .byWordWrapping
        previewLabel.cell?.truncatesLastVisibleLine = true
        previewLabel.translatesAutoresizingMaskIntoConstraints = false
        // Approximate text width so the first layout pass already reserves two lines; refined in layout().
        previewLabel.preferredMaxLayoutWidth = 340
        self.previewLabel = previewLabel

        let textStack = NSStackView(views: [timeLabel, previewLabel])
        textStack.orientation = .vertical
        textStack.alignment = .leading
        textStack.spacing = 2
        textStack.translatesAutoresizingMaskIntoConstraints = false

        let thumb = NSImageView()
        thumb.imageScaling = .scaleProportionallyUpOrDown
        thumb.wantsLayer = true
        thumb.layer?.cornerRadius = 6
        thumb.layer?.masksToBounds = true
        thumb.translatesAutoresizingMaskIntoConstraints = false
        let hasImage: Bool
        if let data = entry.imageData, let image = NSImage(data: data) {
            thumb.image = image
            hasImage = true
        } else {
            hasImage = false
        }

        let actions = NSStackView(views: [pinButton, deleteButton])
        actions.orientation = .horizontal
        actions.spacing = 0
        actions.translatesAutoresizingMaskIntoConstraints = false

        addSubview(thumb)
        addSubview(textStack)
        addSubview(actions)
        NSLayoutConstraint.activate([
            thumb.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 12),
            thumb.centerYAnchor.constraint(equalTo: centerYAnchor),
            thumb.widthAnchor.constraint(equalToConstant: hasImage ? 44 : 0),
            thumb.heightAnchor.constraint(equalToConstant: 44),
            textStack.leadingAnchor.constraint(equalTo: thumb.trailingAnchor, constant: hasImage ? 10 : 0),
            textStack.trailingAnchor.constraint(equalTo: actions.leadingAnchor, constant: -8),
            textStack.centerYAnchor.constraint(equalTo: centerYAnchor),
            textStack.topAnchor.constraint(greaterThanOrEqualTo: topAnchor, constant: 4),
            textStack.bottomAnchor.constraint(lessThanOrEqualTo: bottomAnchor, constant: -4),
            previewLabel.widthAnchor.constraint(equalTo: textStack.widthAnchor),
            timeLabel.widthAnchor.constraint(equalTo: textStack.widthAnchor),
            actions.widthAnchor.constraint(equalToConstant: 56),
            actions.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -8),
            actions.centerYAnchor.constraint(equalTo: centerYAnchor)
        ])
        if !hasImage { thumb.isHidden = true }
        updateActions()
        setAccessibilityElement(true)
        setAccessibilityRole(.button)
        setAccessibilityLabel("\(activity) \(Self.previewText(for: entry))")
    }

    required init?(coder: NSCoder) { fatalError("init(coder:) is not used") }

    private static func previewText(for entry: ClipEntry) -> String {
        guard let text = entry.text else { return "รูปภาพ" }
        let lines = String(text.prefix(400))
            .split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        return lines.isEmpty ? "(ช่องว่าง)" : lines.joined(separator: " ↵ ")
    }

    private func updateActions() {
        deleteButton.alphaValue = isHovering ? 1 : 0
        pinButton.alphaValue = (isHovering || isPinned) ? 1 : 0
    }

    @objc private func pinClicked() { onPin?() }
    @objc private func deleteClicked() { onDelete?() }

    // A wrapping label only reports a 2-line height once it knows its final width.
    override func layout() {
        super.layout()
        guard let label = previewLabel, label.preferredMaxLayoutWidth != label.frame.width else { return }
        label.preferredMaxLayoutWidth = label.frame.width
        label.invalidateIntrinsicContentSize()
        super.layout()
    }

    override var wantsUpdateLayer: Bool { true }

    override func updateLayer() {
        let color = isHovering ? NSColor.labelColor.withAlphaComponent(0.07) : NSColor.clear
        effectiveAppearance.performAsCurrentDrawingAppearance {
            layer?.backgroundColor = color.cgColor
        }
    }

    override func updateTrackingAreas() {
        super.updateTrackingAreas()
        for area in trackingAreas { removeTrackingArea(area) }
        addTrackingArea(NSTrackingArea(
            rect: .zero,
            options: [.mouseEnteredAndExited, .activeAlways, .inVisibleRect],
            owner: self,
            userInfo: nil
        ))
    }

    override func mouseEntered(with event: NSEvent) { isHovering = true }
    override func mouseExited(with event: NSEvent) { isHovering = false }

    override func resetCursorRects() {
        addCursorRect(bounds, cursor: .pointingHand)
    }

    // Buttons are hit-tested first; only clicks on the row body reach here. One click pastes.
    override func mouseDown(with event: NSEvent) {}

    override func mouseUp(with event: NSEvent) {
        if bounds.contains(convert(event.locationInWindow, from: nil)) { onPaste?() }
    }

    override func accessibilityPerformPress() -> Bool {
        onPaste?()
        return true
    }
}


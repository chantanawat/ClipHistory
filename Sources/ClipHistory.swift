        let limitHint = NSTextField(wrappingLabelWithString: "ตั้งได้ \(AppSettings.maxEntriesRange.lowerBound)–\(AppSettings.maxEntriesRange.upperBound) รายการ (ค่าเริ่มต้น \(AppSettings.defaultMaxEntries)) · เมื่อเกิน รายการเก่าสุดจะถูกลบ ส่วนรายการที่ปักหมุดไม่นับและไม่ถูกลบ")
        limitHint.font = .systemFont(ofSize: 11)
        limitHint.textColor = .secondaryLabelColor

        searchToggle.target = self
        searchToggle.action = #selector(searchToggled)
        launchToggle.target = self
        launchToggle.action = #selector(launchToggled)

        let clearButton = NSButton(title: "ล้างประวัติ…", target: self, action: #selector(clearHistory))
        clearButton.bezelStyle = .rounded
        let quitButton = NSButton(title: "ออกจากแอป", target: self, action: #selector(quitApp))
        quitButton.bezelStyle = .rounded
        let buttonRow = NSStackView(views: [clearButton, quitButton])
        buttonRow.orientation = .horizontal
        buttonRow.spacing = 8

        let version = Bundle.main.object(forInfoDictionaryKey: "CFBundleShortVersionString") as? String ?? ""
        let versionLabel = NSTextField(labelWithString: "ClipHistory \(version) · เปิดประวัติด้วย ⌘⇧V")
        versionLabel.font = .systemFont(ofSize: 11)
        versionLabel.textColor = .secondaryLabelColor

        let stack = NSStackView(views: [limitRow, limitHint, searchToggle, launchToggle, buttonRow, versionLabel])
        stack.orientation = .vertical
        stack.alignment = .leading
        stack.spacing = 14
        stack.setCustomSpacing(6, after: limitRow)
        stack.translatesAutoresizingMaskIntoConstraints = false
        settingsPanel.addSubview(stack)
        NSLayoutConstraint.activate([
            stack.leadingAnchor.constraint(equalTo: settingsPanel.leadingAnchor, constant: 16),
            stack.trailingAnchor.constraint(equalTo: settingsPanel.trailingAnchor, constant: -16),
            stack.topAnchor.constraint(equalTo: settingsPanel.topAnchor, constant: 8),
            limitRow.widthAnchor.constraint(equalTo: stack.widthAnchor),
            limitHint.widthAnchor.constraint(equalTo: stack.widthAnchor)
        ])
    }

    override func viewDidLayout() {
        super.viewDidLayout()
        // Keep the single column exactly as wide as the visible area so row buttons never sit past the clip edge.
        tableView.sizeLastColumnToFit()
    }

    private func syncSettingsControls() {
        limitField.integerValue = AppSettings.maxEntries
        limitStepper.integerValue = AppSettings.maxEntries
        searchToggle.state = AppSettings.searchEnabled ? .on : .off
        launchToggle.state = LaunchAtLogin.isEnabled ? .on : .off
    }

    private func applySearchVisibility() {
        let enabled = AppSettings.searchEnabled
        searchField.isHidden = !enabled
        scrollTopWithSearch.isActive = enabled
        scrollTopWithoutSearch.isActive = !enabled
        if !enabled { searchField.stringValue = "" }
    }

    func numberOfRows(in tableView: NSTableView) -> Int { visibleEntries.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        guard visibleEntries.indices.contains(row) else { return nil }
        let entry = visibleEntries[row]
        let id = entry.id
        let rowView = ClipRowView(entry: entry, activity: Self.activityLabel(for: entry))
        rowView.onPaste = { [weak self] in
            guard let self, let entry = self.visibleEntries.first(where: { $0.id == id }) else { return }
            self.onChoose?(entry)
        }
        rowView.onPin = { HistoryStore.shared.togglePin(id: id) }
        rowView.onDelete = { [weak self] in
            guard let entry = self?.visibleEntries.first(where: { $0.id == id }) else { return }
            HistoryStore.shared.delete(entry)
        }
        return rowView
    }

    private static let timestampFormatter: DateFormatter = {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "th_TH")
        formatter.dateStyle = .medium
        formatter.timeStyle = .medium
        return formatter
    }()

    private static func activityLabel(for entry: ClipEntry) -> String {
        let date = entry.lastPastedAt ?? entry.copiedAt
        let action = entry.lastPastedAt == nil ? "คัดลอก" : "วางล่าสุด"
        return "\(action) · \(timestampFormatter.string(from: date))"
    }

    func setScreenshotStatus(_ text: String) {
        screenshotStatusText = text
        if isViewLoaded { screenshotStatusLabel.stringValue = text }
    }

    func setPasteStatus(_ text: String) {
        pasteStatusLabel.stringValue = text
    }

    func prepareForDisplay() {
        guard isViewLoaded else { return }
        pasteStatusLabel.stringValue = ""
        settingsPanel.isHidden = true
        gearButton.contentTintColor = .secondaryLabelColor
        searchField.stringValue = ""
        refresh()
    }

    func focusSearchIfEnabled() {
        guard isViewLoaded, AppSettings.searchEnabled else { return }
        view.window?.makeFirstResponder(searchField)
    }

    @objc private func toggleSettings() {
        settingsPanel.isHidden.toggle()
        gearButton.contentTintColor = settingsPanel.isHidden ? .secondaryLabelColor : .controlAccentColor
        if !settingsPanel.isHidden { syncSettingsControls() }
    }

    @objc private func searchChanged() { refresh() }

    @objc private func searchToggled() {
        AppSettings.searchEnabled = searchToggle.state == .on
        applySearchVisibility()
        refresh()
    }

    @objc private func launchToggled() {
        if !LaunchAtLogin.set(launchToggle.state == .on) { launchToggle.state = LaunchAtLogin.isEnabled ? .on : .off }
    }

    @objc private func limitFieldChanged() { applyLimit(limitField.integerValue) }
    @objc private func limitStepperChanged() { applyLimit(limitStepper.integerValue) }

    private func applyLimit(_ requested: Int) {
        let limit = AppSettings.clamp(requested)
        let overflow = HistoryStore.shared.overflowCount(forLimit: limit)
        if overflow > 5 {
            let alert = NSAlert()
            alert.messageText = "ลดเหลือ \(limit) รายการ?"
            alert.informativeText = "รายการเก่าสุด \(overflow) รายการจะถูกลบ (รายการที่ปักหมุดไม่ถูกลบ)"
            alert.addButton(withTitle: "ลบรายการเก่า")
            alert.addButton(withTitle: "ยกเลิก")
            guard alert.runModal() == .alertFirstButtonReturn else {
                syncSettingsControls()
                return
            }
        }
        AppSettings.maxEntries = limit
        syncSettingsControls()
        HistoryStore.shared.applyLimitChange()
    }

    @objc private func clearHistory() {
        let alert = NSAlert()
        alert.messageText = "ล้างประวัติทั้งหมดหรือไม่?"
        alert.informativeText = "รายการที่เก็บไว้ในเครื่องจะถูกลบ ยกเว้นรายการที่ปักหมุด"
        alert.addButton(withTitle: "ล้างทั้งหมด")
        alert.addButton(withTitle: "ยกเลิก")
        if alert.runModal() == .alertFirstButtonReturn { HistoryStore.shared.clear() }
    }

    @objc private func quitApp() { NSApp.terminate(nil) }

    @objc private func refresh() {
        let all = HistoryStore.shared.entries
        var list = all.filter { $0.isPinned == true } + all.filter { $0.isPinned != true }
        let query = searchField.stringValue.trimmingCharacters(in: .whitespacesAndNewlines)
        let searching = AppSettings.searchEnabled && !query.isEmpty
        if searching {
            list = list.filter { ($0.text ?? "รูปภาพ").localizedStandardContains(query) }
        }
        visibleEntries = list
        tableView.reloadData()
        emptyLabel.stringValue = searching ? "ไม่พบรายการที่ตรงกับคำค้น" : "ยังไม่มีประวัติคลิปบอร์ด"
        emptyLabel.isHidden = !visibleEntries.isEmpty
    }
}

private let hotKeyHandler: EventHandlerProcPtr = { _, event, userData in
    guard let event, GetEventKind(event) == UInt32(kEventHotKeyPressed), let userData else { return noErr }
    let delegate = Unmanaged<AppDelegate>.fromOpaque(userData).takeUnretainedValue()
    DispatchQueue.main.async { delegate.toggleHistory() }
    return noErr
}

private final class AppDelegate: NSObject, NSApplicationDelegate, NSPopoverDelegate {
    private var statusItem: NSStatusItem!
    private let popover = NSPopover()
    private var hotKey: EventHotKeyRef?
    private var eventHandler: EventHandlerRef?
    private var captureTimer: Timer?
    private var screenshotTimer: Timer?
    private var screenshotFolder = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop", isDirectory: true)
    private var knownScreenshotPaths = Set<String>()
    private let launchTime = Date()
    private var historyController: HistoryViewController!
    private var targetApplication: NSRunningApplication?
    private var pasteInProgress = false
    private var pendingPaste: (target: NSRunningApplication, entry: ClipEntry)?

    func applicationDidFinishLaunching(_ notification: Notification) {
        NSApp.setActivationPolicy(.accessory)
        NSWorkspace.shared.notificationCenter.addObserver(
            self,
            selector: #selector(activeApplicationChanged(_:)),
            name: NSWorkspace.didActivateApplicationNotification,
            object: nil
        )
        targetApplication = NSWorkspace.shared.frontmostApplication
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.title = "▣"
        statusItem.button?.toolTip = "ClipHistory — ⌘⇧V"
        statusItem.button?.target = self
        statusItem.button?.action = #selector(toggleHistory)

        historyController = HistoryViewController()
        historyController.onChoose = { [weak self] entry in self?.paste(entry) }
        popover.contentViewController = historyController
        popover.delegate = self
        popover.behavior = .transient
        popover.contentSize = NSSize(width: 460, height: 600)
        registerHotKey()

        captureTimer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { _ in
            HistoryStore.shared.capturePasteboard()
        }
        captureTimer?.tolerance = 0.1
        startScreenshotWatcher()
        HistoryStore.shared.capturePasteboard()
    }

    @objc private func activeApplicationChanged(_ notification: Notification) {
        guard let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
              app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return }
        targetApplication = app
    }

    private func startScreenshotWatcher() {
        refreshScreenshotFolder()
        screenshotTimer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            self?.captureNewScreenshots()
        }
        screenshotTimer?.tolerance = 0.2
    }

    private func captureNewScreenshots() {
        refreshScreenshotFolder()
        guard let files = try? FileManager.default.contentsOfDirectory(at: screenshotFolder, includingPropertiesForKeys: [.contentModificationDateKey, .isRegularFileKey], options: .skipsHiddenFiles) else {
            let displayPath = screenshotFolder.path.replacingOccurrences(of: FileManager.default.homeDirectoryForCurrentUser.path + "/", with: "")
            historyController.setScreenshotStatus("ไม่สามารถอ่านโฟลเดอร์ภาพหน้าจอ \(displayPath) — อนุญาตใน System Settings → Privacy & Security → Files & Folders")
            return
        }
        let displayPath = screenshotFolder.path.replacingOccurrences(of: FileManager.default.homeDirectoryForCurrentUser.path + "/", with: "")
        historyController.setScreenshotStatus("กำลังติดตามโฟลเดอร์ภาพหน้าจอ: \(displayPath)")
        for file in files where isScreenshotFile(file) && !knownScreenshotPaths.contains(file.path) {
            let modified = (try? file.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate ?? .distantPast
            guard modified >= launchTime.addingTimeInterval(-1) else {
                knownScreenshotPaths.insert(file.path)
                continue
            }
            if HistoryStore.shared.captureScreenshot(at: file) {
                knownScreenshotPaths.insert(file.path)
            }
        }
    }

    private func refreshScreenshotFolder() {
        let preference = CFPreferencesCopyAppValue("location" as CFString, "com.apple.screencapture" as CFString) as? String
            ?? UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location")
        let nextFolder: URL
        if let preference, !preference.isEmpty {
            if let url = URL(string: preference), url.isFileURL {
                nextFolder = url.standardizedFileURL
            } else {
                nextFolder = URL(fileURLWithPath: (preference as NSString).expandingTildeInPath, isDirectory: true).standardizedFileURL
            }
        } else {
            nextFolder = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop", isDirectory: true)
        }
        guard nextFolder.path != screenshotFolder.standardizedFileURL.path else { return }
        screenshotFolder = nextFolder
        if let existing = try? FileManager.default.contentsOfDirectory(at: screenshotFolder, includingPropertiesForKeys: [.contentModificationDateKey], options: .skipsHiddenFiles) {
            for file in existing where isScreenshotFile(file) {
                let modified = (try? file.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate ?? .distantPast
                if modified < launchTime.addingTimeInterval(-1) { knownScreenshotPaths.insert(file.path) }
            }
        }
    }

    private func isScreenshotFile(_ url: URL) -> Bool {
        let name = url.deletingPathExtension().lastPathComponent.lowercased()
        let isScreenshotName = ["screen shot", "screenshot", "screen capture", "screencapture", "ภาพหน้าจอ", "ภาพถ่ายหน้าจอ"].contains { name.contains($0) }
        let isImage = ["png", "jpg", "jpeg", "tif", "tiff", "heic"].contains(url.pathExtension.lowercased())
        return isScreenshotName && isImage
    }

    @objc func toggleHistory() {
        guard let button = statusItem.button else { return }
        if popover.isShown {
            popover.performClose(nil)
        } else {
            let frontmost = NSWorkspace.shared.frontmostApplication
            if frontmost?.processIdentifier != ProcessInfo.processInfo.processIdentifier {
                targetApplication = frontmost
            }
            historyController.prepareForDisplay()
            popover.show(relativeTo: button.bounds, of: button, preferredEdge: .minY)
            popover.contentViewController?.view.window?.makeKey()
            historyController.focusSearchIfEnabled()
        }
    }

    private func registerHotKey() {
        var eventType = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), hotKeyHandler, 1, &eventType, Unmanaged.passUnretained(self).toOpaque(), &eventHandler)
        let identifier = EventHotKeyID(signature: OSType(0x434C4950), id: 1)
        let status = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | shiftKey), identifier, GetApplicationEventTarget(), 0, &hotKey)
        if status != noErr { NSLog("ClipHistory: shortcut ⌘⇧V could not be registered (%d)", status) }
    }

    private func paste(_ entry: ClipEntry) {
        guard !pasteInProgress else { return }
        pasteInProgress = true
        guard ClipboardWriter.write(text: entry.text, imageData: entry.imageData, imageType: entry.imageType) else {
            pasteInProgress = false
            historyController.setPasteStatus("คัดลอกไปยังคลิปบอร์ดไม่สำเร็จ")
            return
        }
        HistoryStore.shared.markCurrentPasteboardHandled()
        guard let targetApplication, !targetApplication.isTerminated else {
            pasteInProgress = false
            historyController.setPasteStatus("คัดลอกแล้ว · ไม่พบแอปปลายทาง กด ⌘V เพื่อวาง")
            return
        }
        waitForPasteAccess(targetApplication, entry: entry, attemptsRemaining: 120, requestedAccessibility: false, requestedPostEvent: false)
    }

    private func waitForPasteAccess(
        _ target: NSRunningApplication,
        entry: ClipEntry,
        attemptsRemaining: Int,
        requestedAccessibility: Bool,
        requestedPostEvent: Bool
    ) {
        guard attemptsRemaining > 0 else {
            pasteInProgress = false
            historyController.setPasteStatus("ยังไม่ได้รับสิทธิ์วางอัตโนมัติ · อนุญาต ClipHistory ใน Accessibility")
            NSLog("ClipHistory: timed out waiting for paste permission")
            return
        }
        if !AXIsProcessTrusted() {
            if !requestedAccessibility {
                let promptKey = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
                _ = AXIsProcessTrustedWithOptions([promptKey: true] as CFDictionary)
                historyController.setPasteStatus("กำลังรอสิทธิ์ Accessibility สำหรับ ClipHistory")
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
                self?.waitForPasteAccess(target, entry: entry, attemptsRemaining: attemptsRemaining - 1, requestedAccessibility: true, requestedPostEvent: requestedPostEvent)
            }
            return
        }
        if !CGPreflightPostEventAccess() {
            if !requestedPostEvent {
                _ = CGRequestPostEventAccess()
                historyController.setPasteStatus("กำลังรอสิทธิ์ส่งคำสั่งวางสำหรับ ClipHistory")
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
                self?.waitForPasteAccess(target, entry: entry, attemptsRemaining: attemptsRemaining - 1, requestedAccessibility: requestedAccessibility, requestedPostEvent: true)
            }
            return
        }
        pendingPaste = (target, entry)
        if popover.isShown {
            popover.performClose(nil)
        } else {
            beginPendingPaste()
        }
    }

    func popoverDidClose(_ notification: Notification) {
        beginPendingPaste()
    }

    private func beginPendingPaste() {
        guard let pendingPaste else { return }
        self.pendingPaste = nil
        if #available(macOS 14.0, *) {
            _ = pendingPaste.target.activate(options: [.activateAllWindows])
        } else {
            _ = pendingPaste.target.activate(options: [.activateAllWindows, .activateIgnoringOtherApps])
        }
        waitForTargetAndPaste(pendingPaste.target, entry: pendingPaste.entry, attemptsRemaining: 30)
    }

    private func waitForTargetAndPaste(_ target: NSRunningApplication, entry: ClipEntry, attemptsRemaining: Int) {
        guard !target.isTerminated else {
            pasteInProgress = false
            NSLog("ClipHistory: target app closed before paste")
            return
        }
        if NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { [weak self] in
                guard let self else { return }
                guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier else {
                    self.waitForTargetAndPaste(target, entry: entry, attemptsRemaining: attemptsRemaining - 1)
                    return
                }
                self.postPaste(entry)
            }
            return
        }
        guard attemptsRemaining > 0 else {
            pasteInProgress = false
            NSLog("ClipHistory: target app did not become active before paste")
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { [weak self] in
            self?.waitForTargetAndPaste(target, entry: entry, attemptsRemaining: attemptsRemaining - 1)
        }
    }

    private func postPaste(_ entry: ClipEntry) {
        guard let source = CGEventSource(stateID: .combinedSessionState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else {
            pasteInProgress = false
            NSLog("ClipHistory: could not create paste key events")
            return
        }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        NSLog("ClipHistory: sent paste key events for %@", entry.imageData == nil ? "text" : "image")
        HistoryStore.shared.markPasted(entry)
        pasteInProgress = false
    }
}

